export function getStoreByNumber(storeNumber: string): USStoreLocation {
  const found = ALL_USA_STORES.find(s => s.store_number === storeNumber);
  if (found) return found;
  return ALL_USA_STORES.find(s => s.store_number === '4012') || ALL_USA_STORES[0];
}

export function searchStores(query: string, region: string = 'All', stateCode: string = 'All'): USStoreLocation[] {
  return ALL_USA_STORES.filter(s => {
    if (region !== 'All' && s.region !== region) return false;
    if (stateCode !== 'All' && s.state_code !== stateCode) return false;
    if (!query.trim()) return true;

    const q = query.toLowerCase().trim();
    return (
      s.store_number.toLowerCase() === q ||
      s.state_code.toLowerCase() === q ||
      s.store_number.includes(q) ||
      s.name.toLowerCase().includes(q) ||
      s.city.toLowerCase().includes(q) ||
      s.state.toLowerCase().includes(q) ||
      s.zipcode.includes(q) ||
      s.address.toLowerCase().includes(q)
    );
  });
}

export function exportStoresToCSV(stores: USStoreLocation[]): string {
  const headers = [
    "store_number",
    "name",
    "state",
    "state_code",
    "region",
    "city",
    "zipcode",
    "address",
    "phone",
    "type",
    "pickup_eligible",
    "hours",
    "timezone"
  ];
  const escapeCSV = (val: any) => `"${String(val ?? '').replace(/"/g, '""')}"`;
  const headerRow = headers.map(h => `"${h}"`).join(',');
  const rows = stores.map(s => headers.map(h => escapeCSV((s as any)[h])).join(','));
  return [headerRow, ...rows].join('\n');
}

